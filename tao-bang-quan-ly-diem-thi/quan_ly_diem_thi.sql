-- THUC HANH: TAO BANG TRONG CSDL QUAN LY DIEM THI
-- Chay toan bo file trong MySQL Workbench.

CREATE DATABASE IF NOT EXISTS QuanLyDiemThi
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE QuanLyDiemThi;

CREATE TABLE IF NOT EXISTS HocSinh (
  MaHS VARCHAR(20) PRIMARY KEY,
  TenHS VARCHAR(50),
  NgaySinh DATETIME,
  Lop VARCHAR(20),
  GT VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS GiaoVien (
  MaGV VARCHAR(20) PRIMARY KEY,
  TenGV VARCHAR(50),
  SDT VARCHAR(10)
);

-- MaMH dung VARCHAR(50) theo bang mo ta de khop khoa ngoai o BangDiem.
CREATE TABLE IF NOT EXISTS MonHoc (
  MaMH VARCHAR(50) PRIMARY KEY,
  TenMH VARCHAR(50),
  MaGV VARCHAR(20),
  CONSTRAINT FK_MonHoc_GiaoVien
    FOREIGN KEY (MaGV) REFERENCES GiaoVien(MaGV)
);

CREATE TABLE IF NOT EXISTS BangDiem (
  MaHS VARCHAR(20),
  MaMH VARCHAR(50),
  DiemThi INT,
  NgayKT DATETIME,
  PRIMARY KEY (MaHS, MaMH),
  CONSTRAINT FK_BangDiem_HocSinh
    FOREIGN KEY (MaHS) REFERENCES HocSinh(MaHS),
  CONSTRAINT FK_BangDiem_MonHoc
    FOREIGN KEY (MaMH) REFERENCES MonHoc(MaMH)
);

-- Kiem tra cac bang, cot va khoa ngoai
