CREATE DATABASE IF NOT EXISTS QuanLyVatTu CHARACTER SET utf8mb4;
USE QuanLyVatTu;
CREATE TABLE PhieuXuat (SoPX VARCHAR(20) PRIMARY KEY, NgayXuat DATE);
CREATE TABLE VatTu (MaVTU VARCHAR(20) PRIMARY KEY, TenVTU VARCHAR(100));
CREATE TABLE PhieuNhap (SoPN VARCHAR(20) PRIMARY KEY, NgayNhap DATE);
CREATE TABLE NhaCC (MaNCC VARCHAR(20) PRIMARY KEY, TenNCC VARCHAR(100), DiaChi VARCHAR(255));
CREATE TABLE DonDH (SoDH VARCHAR(20) PRIMARY KEY, NgayDH DATE, MaNCC VARCHAR(20), FOREIGN KEY (MaNCC) REFERENCES NhaCC(MaNCC));
CREATE TABLE CT_PhieuXuat (SoPX VARCHAR(20), MaVTU VARCHAR(20), DGXuat DECIMAL(15,2), SLXuat INT,
 PRIMARY KEY(SoPX,MaVTU), FOREIGN KEY(SoPX) REFERENCES PhieuXuat(SoPX), FOREIGN KEY(MaVTU) REFERENCES VatTu(MaVTU));
CREATE TABLE CT_PhieuNhap (SoPN VARCHAR(20), MaVTU VARCHAR(20), DGNhap DECIMAL(15,2), SLNhap INT,
 PRIMARY KEY(SoPN,MaVTU), FOREIGN KEY(SoPN) REFERENCES PhieuNhap(SoPN), FOREIGN KEY(MaVTU) REFERENCES VatTu(MaVTU));
CREATE TABLE CT_DonDH (SoDH VARCHAR(20), MaVTU VARCHAR(20),
 PRIMARY KEY(SoDH,MaVTU), FOREIGN KEY(SoDH) REFERENCES DonDH(SoDH), FOREIGN KEY(MaVTU) REFERENCES VatTu(MaVTU));
CREATE TABLE NhaCC_SDT (MaNCC VARCHAR(20), SDT VARCHAR(20),
 PRIMARY KEY(MaNCC,SDT), FOREIGN KEY(MaNCC) REFERENCES NhaCC(MaNCC));
